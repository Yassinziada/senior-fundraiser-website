import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createUser, as, rpc } from './db-helpers.js';

export async function checkMoney(pool) {
 const checks=[]; const ids={};
 for(const role of ['admin','finance','cashier','product_manager','supplier']) ids[role]=await createUser(pool,{email:`money-${role}@test.local`,username:`money-${role}`,role,section:role==='cashier'?'BAZAAR':null});
 const product=await rpc(pool,ids.admin,'admin_save_product',[JSON.stringify({section_code:'BAZAAR',name:'Money water',price:30,cost:20,starting_stock:1})]);
 const sale=async(q=1,method='CASH',key=randomUUID())=>rpc(pool,ids.cashier,'pos_checkout',[key,JSON.stringify([{product_id:product,quantity:q}]),method,method==='CASH'?1000:null,q*30,null]);
 await sale(); // excluded from opening cash and profit
 const summary=async()=>rpc(pool,ids.finance,'money_summary');
 assert.equal((await summary()).started_at,null);
 for(const role of ['finance','cashier','product_manager','supplier']) await assert.rejects(rpc(pool,ids[role],'money_open',[randomUUID(),1000,0,0]),/admin/i);
 for(const role of ['cashier','product_manager','supplier']) await assert.rejects(rpc(pool,ids[role],'money_summary'),/cannot perform/i);
 const key=randomUUID(); await rpc(pool,ids.admin,'money_open',[key,1000,100,50]); await rpc(pool,ids.admin,'money_open',[key,1000,100,50]);
 await assert.rejects(rpc(pool,ids.admin,'money_open',[randomUUID(),1000,100,50]),/already/i);
 assert.equal(Number((await summary()).total),1150); assert.equal(Number((await summary()).sales),0);
 checks.push('Admin-only opening, safe opening retries, no historical sales double count');
 const stock=async()=>Number((await pool.query('select stock from products where id=$1',[product])).rows[0].stock);
 const receive=async(q,c=20,account='CASH',key=randomUUID(),item=null,no=false,mode='add')=>rpc(pool,ids.product_manager,'money_stock',[key,product,mode,q,'Actual receipt',no?null:c,no?null:account,no,item]);
 await assert.rejects(rpc(pool,ids.admin,'admin_adjust_stock',[product,'add',1,'Old client']),/Refresh/i);
 await assert.rejects(rpc(pool,ids.admin,'_stock_adjust_original',[product,'add',1,'Bypass']),/permission/i);
 for(const role of ['finance','cashier','supplier']) await assert.rejects(rpc(pool,ids[role],'money_stock',[randomUUID(),product,'add',1,'Forbidden',20,'CASH',false,null]),/cannot perform/i);
 const receipt=randomUUID(); await receive(10,20,'CASH',receipt); await receive(10,20,'CASH',receipt);
 assert.equal(await stock(),10); assert.equal(Number((await summary()).cash),800);
 await assert.rejects(receive(11,20,'CASH',receipt),/different action/i);
 const checkoutKey=randomUUID(); await sale(4,'CASH',checkoutKey); await sale(4,'CASH',checkoutKey);
 let s=await summary(); assert.equal(Number(s.cash),920); assert.equal(Number(s.sales),120); assert.equal(Number(s.gross_profit),40); assert.equal(Number(s.net_profit),40); assert.equal(await stock(),6);
 checks.push('Manual stock deducts once; full sale amount after change adds once; COGS only sold units');
 await assert.rejects(receive(100),/Not enough money/i); assert.equal(await stock(),6);
 await assert.rejects(receive(1,1.001),/two decimal/i); await assert.rejects(receive(1,-1),/valid amount/i);
 await assert.rejects(receive(1,'NaN'),/valid amount/i);
 const expense=randomUUID(); const expenseArgs=[expense,'expense','CASH',10,'Transport',null];
 await rpc(pool,ids.finance,'money_record',expenseArgs); await rpc(pool,ids.finance,'money_record',expenseArgs);
 await rpc(pool,ids.finance,'money_record',[randomUUID(),'transfer','CASH',100,'Move to Telda','TELDA']);
 s=await summary(); assert.equal(Number(s.cash),810); assert.equal(Number(s.telda),200); assert.equal(Number(s.total),1060); assert.equal(Number(s.net_profit),30);
 await assert.rejects(rpc(pool,ids.finance,'money_record',[randomUUID(),'transfer','CASH',1,'Same account','CASH']),/different destination/i);
 await assert.rejects(rpc(pool,ids.supplier,'money_record',[randomUUID(),'expense','CASH',1,'Forbidden',null]),/cannot perform/i);
 checks.push('Expenses reduce cash and net profit once; transfers preserve combined total; insufficient funds rollback');
 await rpc(pool,ids.product_manager,'create_supplier_order',[randomUUID(),ids.supplier,'Money supplies',JSON.stringify([{product_id:product,quantity:5}])]);
 const [item]=await as(pool,ids.supplier,'select * from supplier_order_items');
 await assert.rejects(receive(2,20,'TELDA',randomUUID(),item.id),/supplier must confirm/i);
 await rpc(pool,ids.supplier,'supplier_confirm_purchase',[item.id,5]);
 await assert.rejects(receive(2,20,'TELDA',randomUUID(),item.id),/supplier must confirm/i);
 await rpc(pool,ids.supplier,'supplier_confirm_delivery',[item.id,3]);
 await assert.rejects(receive(4,20,'TELDA',randomUUID(),item.id),/supplier-confirmed delivery/i);
 const sk=randomUUID();await receive(2,20,'TELDA',sk,item.id);await receive(2,20,'TELDA',sk,item.id);
 assert.equal(Number((await summary()).telda),160); assert.equal(await stock(),8);
 assert.equal(Number((await as(pool,ids.product_manager,'select received from supplier_order_items where id=$1',[item.id]))[0].received),2);
 checks.push('Supplier receipt requires purchase+delivery, partial receipt pays actual quantity, safe retry');
 // Average 8 @20 +2 @30 =22, future sale gets22 cost snapshot.
 await receive(2,30,'INSTAPAY').then(()=>assert.fail('InstaPay only has50'),e=>assert.match(e.message,/Not enough money/i));
 await receive(2,30,'CASH');
 assert.equal(Number((await pool.query('select cost from product_costs where product_id=$1',[product])).rows[0].cost),22);
 const tx=await sale(1,'TELDA');
 assert.equal(Number((await summary()).gross_profit),48);
 const [txn]=await pool.query('select id from transactions where idempotency_key=$1',[tx.idempotency_key]).then(r=>r.rows);
 const txnId=txn?.id || tx.id || tx.transaction_id;
 await rpc(pool,ids.admin,'admin_void_transaction',[txnId,'Return goods']);
 assert.equal(Number((await summary()).gross_profit),40);assert.equal(await stock(),10);
 await assert.rejects(rpc(pool,ids.admin,'admin_void_transaction',[txnId,'Repeat return']),/already voided/i);
 assert.equal(Number((await summary()).gross_profit),40);
 await receive(1,null,null,randomUUID(),null,true,'remove');
 assert.equal(Number((await summary()).net_profit),8);
 const cashBefore=Number((await summary()).total);await receive(1,null,null,randomUUID(),null,true);
 assert.equal(Number((await summary()).total),cashBefore);
 checks.push('Average purchase costs, refund reversal, losses affect profit only, free stock has no payment');
 const newKey=randomUUID();const payload={section_code:'BAZAAR',name:'New funded item',price:8,cost:3,starting_stock:2,funding_key:newKey,no_spend:false,payment_account:'CASH'};
 const newProduct=await rpc(pool,ids.product_manager,'admin_save_product',[JSON.stringify(payload)]);
 assert.equal(await rpc(pool,ids.product_manager,'admin_save_product',[JSON.stringify(payload)]),newProduct);
 const afterNew=Number((await summary()).total);assert.equal(afterNew,cashBefore-6);
 await assert.rejects(rpc(pool,ids.product_manager,'admin_save_product',[JSON.stringify({...payload,id:newProduct,cost:10})]),/averaged/i);
 const rows=[{section_code:'BAZAAR',name:'Imported paid',price:10,cost:2,stock:3,funding_key:randomUUID(),payment_account:'CASH',no_spend:false}];
 await rpc(pool,ids.product_manager,'admin_import_products',[JSON.stringify(rows)]);await rpc(pool,ids.product_manager,'admin_import_products',[JSON.stringify(rows)]);
 assert.equal(Number((await summary()).total),afterNew-6);
 checks.push('Initial product stock and imported stock deduct once; catalogue cost edits cannot rewrite owned inventory cost');
 for(const role of ['cashier','supplier','product_manager']) assert.equal((await as(pool,ids[role],'select * from money_ledger')).length,0);
 await assert.rejects(as(pool,ids.finance,"insert into money_ledger(account,amount,kind,note) values('CASH',100,'opening','hack')"),/permission/i);
 await assert.rejects(pool.query('delete from money_ledger'),/append-only/i);
 await assert.rejects(pool.query('truncate money_ledger'),/append-only/i);
 assert.equal(Number((await summary()).total),Number((await summary()).cash)+Number((await summary()).telda)+Number((await summary()).instapay));
 checks.push('Ledger RLS, immutable history, combined total equals all account balances');
 return checks;
}
