// Concatenates the migrations + base seed into ONE file that a beginner can
// paste into the Supabase SQL Editor in a single run:
//   supabase/ALL_IN_ONE_setup.sql
// Run with:  npm run db:bundle
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase');
const migrations = readdirSync(join(root, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const parts = [
  '-- =============================================================================',
  '-- School Bazaar POS — COMPLETE DATABASE SETUP (generated by `npm run db:bundle`)',
  '-- Paste this whole file into Supabase Dashboard -> SQL Editor -> New query -> Run.',
  '-- Run it ONCE on a new, empty project. Do not edit here; edit supabase/migrations.',
  '-- =============================================================================',
  '',
];
for (const f of [...migrations.map((m) => join('migrations', m)), 'seed.sql']) {
  parts.push(`-- >>>>>>>>>> ${f} <<<<<<<<<<`, readFileSync(join(root, f), 'utf8').trim(), '');
}
writeFileSync(join(root, 'ALL_IN_ONE_setup.sql'), parts.join('\n'));
console.log(`Wrote supabase/ALL_IN_ONE_setup.sql from ${migrations.length} migrations + seed.sql`);
